CREATE TABLE IF NOT EXISTS felhasznalok (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    email VARCHAR(254) NOT NULL UNIQUE,
    jelszo_hash VARCHAR(255) NOT NULL,
    session_verzio INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS jelszo_tokenek (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    felhasznalo_id INTEGER NOT NULL REFERENCES felhasznalok(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    lejar DATETIME NOT NULL,
    felhasznalva DATETIME NULL,
    letrehozva DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip VARCHAR(45) NULL
);